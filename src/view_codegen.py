# Image viewport geometry, in fixed-point 1/1024 units.
e.begin('fitview')
e.get(rax,'viewportw');e.mul(rax,rax,1024);e.get(rbx,'vieww');e.div(rbx);e.mov(rsi,rax)
e.get(rax,'viewporth');e.mul(rax,rax,1024);e.get(rbx,'viewh');e.div(rbx);e.cmp(rax,rsi);fl=e.unique();e.jump(fl,'le');e.mov(rax,rsi);e.label(fl)
e.cmpi(rax,1);fl=e.unique();e.jump(fl,'ge');e.imm(rax,1);e.label(fl);e.put('fit',rax);e.put('scale',rax)
zero('vx');zero('vy');e.call('clampview');e.ret()
e.begin('clampview')
for dim,pix,out,pos in [('viewportw','vieww','vw','vx'),('viewporth','viewh','vh','vy')]:
    e.get(rax,pix);e.get(rbx,'scale');e.mul(rax,rbx);e.shift(rax,10);e.put(out,rax);e.get(rbx,dim)
    larger=e.unique();done=e.unique();e.cmp(rax,rbx);e.jump(larger,'g');e.sub(rbx,rax);e.shift(rbx,1)
    if dim=='viewporth':e.get(rcx,'viewtop');e.add(rbx,rcx)
    e.put(pos,rbx);e.jump(done)
    e.label(larger);e.sub(rbx,rax)
    if dim=='viewporth':e.get(rcx,'viewtop');e.add(rbx,rcx)
    e.get(rcx,pos);lo=e.unique();hi=e.unique();e.cmp(rcx,rbx);e.jump(lo,'ge');e.mov(rcx,rbx);e.label(lo)
    if dim=='viewporth':e.get(rdx,'viewtop')
    else:e.imm(rdx,0)
    e.cmp(rcx,rdx);e.jump(hi,'le');e.mov(rcx,rdx);e.label(hi);e.put(pos,rcx);e.label(done)
e.ret()
