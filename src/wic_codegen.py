# WIC decode(filename, maximum width, 0 = original). Returns HBITMAP or zero.
# Outputs dw/dh. COM interfaces and partial bitmaps are released on all failures.
e.begin('decode');e.mov(r12,rcx);e.put('maxwidth',rdx)
for n in ['dec','frame','scaler','conv','decodebmp','pixels']:zero(n)
e.com(G('factory'),3,R(r12),0,0x80000000,0,A('dec'));e.check('decodefail')
e.com(G('dec'),13,0,A('frame'));e.check('decodefail')
zero('dw');zero('dh');e.com(G('frame'),3,A('dw'),A('dh'));e.check('decodefail')
e.call('readmetadata',G('metatarget'))
e.get(rbx,'dw');e.get(rsi,'dh');e.cmpi(rbx,1);e.jump('decodefail','l');e.cmpi(rsi,1);e.jump('decodefail','l')
e.set('source',G('frame'));e.get(rdi,'maxwidth');e.test(rdi);e.jump('noscale','e');e.cmp(rbx,rdi);e.jump('noscale','le')
e.mov(rax,rsi);e.mul(rax,rdi);e.div(rbx);e.cmpi(rax,1);ok=e.unique();e.jump(ok,'ge');e.imm(rax,1);e.label(ok);e.put('dh',rax);e.put('dw',rdi)
e.com(G('factory'),11,A('scaler'));e.check('decodefail')
e.com(G('scaler'),8,G('frame'),G('dw'),G('dh'),3);e.check('decodefail');e.set('source',G('scaler'))
e.label('noscale')
e.get(rax,'dw');e.get(rbx,'dh');e.mul(rax,rbx);e.cmpi(rax,200000000);e.jump('decodefail','g')
e.com(G('factory'),10,A('conv'));e.check('decodefail')
e.com(G('conv'),8,G('source'),A('bgra'),0,0,0,0);e.check('decodefail')
e.set('bmi',G('dw'),4,0);e.imm(rax,0);e.get(rbx,'dh');e.sub(rax,rbx);e.put('bmi',rax,8,0)
e.call(D+'CreateDIBSection',0,A('bmi'),0,A('pixels'),0,0);e.put('decodebmp',rax);e.test(rax);e.jump('decodefail','e')
e.get(rbx,'dw');e.mul(rbx,rbx,4);e.get(rsi,'dh');e.mul(rsi,rbx)
e.com(G('conv'),7,0,R(rbx),R(rsi),G('pixels'));e.check('decodefail');e.jump('decodedone')
e.label('decodefail');delobj('decodebmp')
e.label('decodedone')
for n in ['conv','scaler','frame','dec']:release(n)
e.get(rax,'decodebmp');e.ret()
